    private void addRoomJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addRoomJButtonActionPerformed
        // TODO add your handling code here:
        // get data from the text fields and combo boxes
        String roomNumberString = roomNumberJTextField.getText();
        boolean ac = ACJRadioButton.isSelected();
        String roomType = ac ? "AC" : "Non-AC";
        String bed = (String) bedJComboBox.getSelectedItem();
        String priceString = priceJTextField.getText();
        String availability = "Available"; // set status to "Available" by default
        String clean = "Clean"; // set status to "Clean" by default

        // check if room number and price are not empty
        if (roomNumberString.isEmpty() || priceString.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a valid room number and price.");
            return;
        }

        // attempt to parse the price as a double
        double priceDouble;
        try {
            priceDouble = Double.parseDouble(priceString);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid price.");
            return;
        }

        // attempt to parse the room number as an integer
        int roomNumber;
        try {
            roomNumber = Integer.parseInt(roomNumberString);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid room number.");
            return;
        }

        // check if the room number already exists
        for (Room room : Data.rooms) {
            if (room.getRoomNumber() == roomNumber) {
                JOptionPane.showMessageDialog(this, "Room number already exists.");
                return;
            }
        }

        // create a new Room object and add it to the Data.rooms ArrayList
        Room newRoom = new Room(roomNumber, ac, bed, priceDouble);
        Data.rooms.add(newRoom);

        // add a new row to the jTable1 table
        Object[] row = {roomNumber, roomType, bed, priceDouble, availability, clean};
        DefaultTableModel model = (DefaultTableModel) manageRoomJTable.getModel();
        model.addRow(row);
        JOptionPane.showMessageDialog(this, "Room added successfully!");

        // clear the text fields
        roomNumberJTextField.setText("");
        priceJTextField.setText("");

    }//GEN-LAST:event_addRoomJButtonActionPerformed

