    private void deleteRoomJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteRoomJButtonActionPerformed
        // TODO add your handling code here:
        int row = manageRoomJTable.getSelectedRow();
        if (row >= 0) {
            int result = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this room?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
            if (result == JOptionPane.YES_OPTION) {
                DefaultTableModel model = (DefaultTableModel) manageRoomJTable.getModel();
                model.removeRow(row);
                JOptionPane.showMessageDialog(this, "Room deleted successfully.");
            }
        } else {
            JOptionPane.showMessageDialog(this, "Please select a room to delete.");
        }

        
    }//GEN-LAST:event_deleteRoomJButtonActionPerformed

